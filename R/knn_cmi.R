# kNN conditional mutual information (Frenzel-Pompe / KSG) ------------------
# The estimator and the neighbour searches run in C++ (src/knn.cpp, brute
# force O(n^2 d) in the max-norm).  The pure-R versions below (.dist_block,
# .kth_row, .cmi_dist, .knn_cmi_r) are kept as the reference implementation
# that the tests compare against.

.dist_block <- function(M) {
  M <- as.matrix(M)
  D <- matrix(0, nrow(M), nrow(M))
  for (j in seq_len(ncol(M))) D <- pmax(D, abs(outer(M[, j], M[, j], "-")))
  D
}

.kth_row <- function(D, k) {
  diag(D) <- Inf
  apply(D, 1, function(r) sort.int(r, partial = k)[k])
}

# CMI from precomputed max-norm block distance matrices
.cmi_dist <- function(Dx, Dy, Dz, k, Dyz = pmax(Dy, Dz)) {
  eps <- .kth_row(pmax(Dx, Dyz), k)
  nxz <- rowSums(pmax(Dx, Dz) < eps) - 1L
  nyz <- rowSums(Dyz < eps) - 1L
  nz <- rowSums(Dz < eps) - 1L
  digamma(k) - mean(digamma(nxz + 1) + digamma(nyz + 1) - digamma(nz + 1))
}

#' k-nearest-neighbour conditional mutual information
#'
#' Frenzel-Pompe estimator (max-norm) of I(X; Y | Z) in nats; with
#' `z = NULL` it reduces to the Kraskov-Stoegbauer-Grassberger estimator of
#' I(X; Y).
#'
#' @param x,y numeric vectors / matrices (rows = observations).
#' @param z optional conditioning matrix.
#' @param k number of neighbours.
#' @return The CMI estimate (can be slightly negative for independent data).
#' @references
#' Frenzel, S. and Pompe, B. (2007). Partial mutual information for coupling analysis of multivariate time series. *Physical Review Letters*, 99, 204101. \doi{10.1103/PhysRevLett.99.204101}
#'
#' Kraskov, A., Stoegbauer, H. and Grassberger, P. (2004). Estimating mutual information. *Physical Review E*, 69, 066138. \doi{10.1103/PhysRevE.69.066138}
#' @export
#' @examples
#' # y = x + noise: the mutual information of x and y is about 0.35 nats;
#' # z is independent of both, so I(x; z | y) is about 0
#' set.seed(1); x <- rnorm(400); y <- x + rnorm(400); z <- rnorm(400)
#' knn_cmi(x, y)
#' knn_cmi(x, z, y)
knn_cmi <- function(x, y, z = NULL, k = 5L) {
  x <- .num_mat(x); y <- .num_mat(y)
  n <- nrow(x)
  if (nrow(y) != n) stop("x and y must have the same number of rows.", call. = FALSE)
  z <- if (is.null(z)) matrix(numeric(0), n, 0) else .jit(.num_mat(z))
  cmi_knn_cpp(.jit(x), .jit(y), z, as.integer(k))
}

.num_mat <- function(m) { m <- as.matrix(m); storage.mode(m) <- "double"; m }
.jit <- function(m) if (length(m)) m + matrix(stats::rnorm(length(m), 0, 1e-10), nrow(m)) else m
# column-wise standardisation (the max-norm kNN estimators are not invariant
# to rescaling one variable alone); constant columns are centred only
.std <- function(v) { v <- as.numeric(v); s <- stats::sd(v); if (!is.finite(s) || s == 0) v - mean(v) else (v - mean(v)) / s }
.std_mat <- function(m) { m <- .num_mat(m); if (length(m)) m[] <- apply(m, 2, .std); m }

# pure-R reference implementation (tests only)
.knn_cmi_r <- function(x, y, z = NULL, k = 5L) {
  x <- as.matrix(x); y <- as.matrix(y); n <- nrow(x)
  Dx <- .dist_block(x); Dy <- .dist_block(y)
  Dz <- if (is.null(z)) matrix(0, n, n) else .dist_block(as.matrix(z))
  .cmi_dist(Dx, Dy, Dz, as.integer(k))
}

# local permutation (Runge 2018): permute x within k_perm neighbours in z-space
# (nn: 1-based neighbour index matrix ordered by distance; the random draws
# come from R so that seeds and parallel streams stay reproducible)
.local_perm <- function(nn, kp) {
  n <- nrow(nn); kp <- min(as.integer(kp), ncol(nn))
  local_perm_cpp(nn, kp, sample.int(n), stats::runif(n))
}

#' Conditional independence test: kNN-CMI with local permutation null
#'
#' Tests X independent of Y given Z. The null distribution is generated by
#' permuting X among the `k_perm` nearest neighbours of each point in
#' Z-space (Runge, 2018), preserving the X-Z dependence.
#'
#' @inheritParams knn_cmi
#' @param n_perm number of permutations.
#' @param k_perm neighbourhood size for the local permutation.
#' @param cores CPU cores for the permutations (`1` = serial, an integer,
#'   `"auto"` or a cluster; results do not depend on it, see
#'   [Rcausality-parallel]).
#' @param standardize standardise every column of `x`, `y` and `z` first
#'   (default). The max-norm neighbour search is not invariant to rescaling
#'   one variable alone, so the test would otherwise depend on the units.
#' @return A list with `cmi`, `p_value`, `null` (permuted CMIs).
#' @references
#' Runge, J. (2018). Conditional independence testing based on a nearest-neighbor estimator of conditional mutual information. *Proceedings of the 21st International Conference on Artificial Intelligence and Statistics (AISTATS)*, PMLR 84, 938-947.
#'
#' Frenzel, S. and Pompe, B. (2007). Partial mutual information for coupling analysis of multivariate time series. *Physical Review Letters*, 99, 204101. \doi{10.1103/PhysRevLett.99.204101}
#' @export
#' @examples
#' # x and y share the common cause z.  Unconditionally they are dependent;
#' # conditionally on z they are independent, and the local permutation test
#' # (which permutes x within neighbourhoods of z) gives a large p-value.
#' set.seed(2); z <- rnorm(300); x <- z + rnorm(300, 0, .5); y <- z + rnorm(300, 0, .5)
#' local_permutation_test(x, y, n_perm = 50)$p_value       # small: dependent
#' local_permutation_test(x, y, z, n_perm = 50)$p_value    # large: independent given z
local_permutation_test <- function(x, y, z = NULL, k = 5L, k_perm = 5L, n_perm = 100L, cores = getOption("Rcausality.cores", 1L),
                                   standardize = TRUE) {
  prep <- if (standardize) .std_mat else .num_mat
  x <- .jit(prep(x)); y <- .jit(prep(y)); n <- nrow(x)
  z <- if (is.null(z)) matrix(numeric(0), n, 0) else .jit(prep(z))
  k <- as.integer(k)
  obs <- cmi_knn_cpp(x, y, z, k)
  nn <- if (ncol(z) == 0L) NULL else knn_idx_cpp(z, max(as.integer(k_perm), 1L))
  null <- unlist(.plapply(seq_len(n_perm), function(b) {
    perm <- if (is.null(nn)) sample.int(n) else .local_perm(nn, k_perm)
    cmi_knn_cpp(x[perm, , drop = FALSE], y, z, k)
  }, cores = cores))
  list(cmi = obs, p_value = (1 + sum(null >= obs)) / (n_perm + 1), null = null)
}

# Directed CMI test for one ordered pair, scanning lags ---------------------
# I(cause[t-tau]; effect[t] | effect history, [cause history before t-tau],
#   [controls history]);  `cause_past = TRUE` adds the cause's own past
# (full transfer-entropy-type conditioning, Zlatniczki et al. 2021).
.hist_cols <- function(v, t_idx, history, shift = 0L) {
  do.call(cbind, lapply(seq_len(history), function(l) v[t_idx - shift - l]))
}

# The pair is tested over all candidate lags at once: the p-value of the
# maximal CMI over the lags against the maximum of the permuted CMIs (the
# per-lag nulls are drawn independently, which makes the max test
# conservative; no Bonferroni factor is needed).  Series are standardised.
.cmi_pair <- function(effect, cause, controls, lags, history, k, k_perm, n_perm,
                      cause_past = FALSE, cores = 1L) {
  effect <- .std(effect); cause <- .std(cause)
  if (!is.null(controls)) controls <- .std_mat(controls)
  n <- length(effect)
  Lmax <- if (cause_past) max(lags) + history else max(lags, history)
  t_idx <- (Lmax + 1):n
  yt <- effect[t_idx]
  Z <- .hist_cols(effect, t_idx, history)
  if (!is.null(controls))
    Z <- cbind(Z, do.call(cbind, lapply(seq_len(ncol(controls)),
                                        function(j) .hist_cols(controls[, j], t_idx, history))))
  res <- lapply(lags, function(tau) {
    xt <- cause[t_idx - tau]
    Zt <- if (cause_past) cbind(Z, .hist_cols(cause, t_idx, history, shift = tau)) else Z
    local_permutation_test(xt, yt, Zt, k = k, k_perm = k_perm, n_perm = n_perm, cores = cores, standardize = FALSE)
  })
  obs <- vapply(res, `[[`, 0, "cmi"); pl <- vapply(res, `[[`, 0, "p_value")
  null_max <- do.call(pmax, lapply(res, `[[`, "null"))
  b <- which.max(obs)
  list(lag = lags[b], statistic = obs[b],
       p_value = (1 + sum(null_max >= obs[b])) / (length(null_max) + 1), n_eff = n - Lmax,
       by_lag = data.frame(lag = lags, cmi = obs, p = pl), null = null_max)
}

# Contemporaneous (k = 0) dependence given both pasts: I(x[t]; y[t] | pasts).
# Evidence of a common driver (or instantaneous causation) in the sense of
# Zlatniczki et al. (2021), Relation 1.
.cmi_instant <- function(x, y, controls, history, k, k_perm, n_perm, cores = 1L) {
  x <- .std(x); y <- .std(y); if (!is.null(controls)) controls <- .std_mat(controls)
  n <- length(y); t_idx <- (history + 1):n
  Z <- cbind(.hist_cols(x, t_idx, history), .hist_cols(y, t_idx, history))
  if (!is.null(controls))
    Z <- cbind(Z, do.call(cbind, lapply(seq_len(ncol(controls)),
                                        function(j) .hist_cols(controls[, j], t_idx, history))))
  r <- local_permutation_test(x[t_idx], y[t_idx], Z, k = k, k_perm = k_perm, n_perm = n_perm, cores = cores, standardize = FALSE)
  list(cmi = r$cmi, p_value = r$p_value, null = r$null)
}

#' Conditional mutual information as a function of the history depth
#'
#' Computes `I(x[t-lag]; y[t] | x and y histories of depth d)` for a sequence
#' of depths `d`. In the framework of Zlatniczki et al. (2021, App. A), for a
#' lag `k` below the minimal driving lag the CMI tends to 0 as the depth grows
#' when there is no hidden common driver, but converges to a positive
#' constant if there is one.
#'
#' @param x,y numeric vectors.
#' @param lag lag `k >= 0` (0 = contemporaneous).
#' @param depths integer vector of history depths.
#' @param k number of neighbours.
#' @return A data frame with columns `depth` and `cmi`.
#' @references
#' Zlatniczki, A., Stippinger, M., Benko, Z., Somogyvari, Z. and Telcs, A. (2021). Relaxation of some confusions about confounders. *Entropy*, 23(11), 1450. \doi{10.3390/e23111450}
#' @export
#' @examples
#' # does conditioning on deeper own pasts remove the dependence of x and y?
#' # For a shared contemporaneous noise it does not: the CMI stays positive
#' set.seed(1); e <- rnorm(400); x <- e + rnorm(400, 0, .5); y <- e + rnorm(400, 0, .5)
#' cmi_convergence(x, y, lag = 0, depths = 1:3)
cmi_convergence <- function(x, y, lag = 0L, depths = 1:4, k = 5L) {
  n <- length(y); dmax <- max(depths)
  t_idx <- (max(dmax, dmax + 0L) + 1L + lag):n
  vals <- vapply(depths, function(d) {
    Z <- cbind(.hist_cols(x, t_idx - lag, d), .hist_cols(y, t_idx, d))
    knn_cmi(x[t_idx - lag], y[t_idx], Z, k = k)
  }, 0)
  data.frame(depth = depths, cmi = vals)
}

#' Lag triangle-inequality check (geodesic spaces)
#'
#' Zlatniczki et al. (2021), Sect. 2.4-2.6: in a geodesic space with constant
#' propagation speed, lags obey the triangle inequality. Given the minimal lags
#' from a candidate common driver L to X and to Y and the lag X -> Y it tells
#' whether L can be a common driver.
#'
#' @param tau_LX,tau_LY,tau_XY minimal lags L->X, L->Y and X->Y.
#' @return One of `"direct driving (no common driver)"` (when
#'   `tau_LY > tau_LX + tau_XY`), `"common driver"` (when
#'   `tau_LY < tau_LX + tau_XY`) or `"ambiguous (confounder / chain L->X->Y)"`.
#' @references
#' Zlatniczki, A., Stippinger, M., Benko, Z., Somogyvari, Z. and Telcs, A. (2021). Relaxation of some confusions about confounders. *Entropy*, 23(11), 1450. \doi{10.3390/e23111450}
#' @export
#' @examples
#' # a common driver at lag 2 cannot produce an apparent x -> y lag of 5 and
#' # y -> x lag of 1 at the same time: the lags must satisfy the triangle rule
#' lag_triangle_check(2, 5, 1)
lag_triangle_check <- function(tau_LX, tau_LY, tau_XY) {
  if (tau_LY > tau_LX + tau_XY) "direct driving (no common driver)"
  else if (tau_LY < tau_LX + tau_XY) "common driver"
  else "ambiguous (confounder / chain L->X->Y)"
}
