# Markov-chain based causal discovery (Stippinger, Benko, Zlatniczki, Telcs
# et al., "Markov chain approach to causality", Mathematics 2023, 11, 852).
#
# Idea: whether X, Y and the joint J = (X, Y) are first-order Markov chains
# (after time-delay embedding), together with a few directed conditional-
# dependence tests, identifies the causal case through the decision tables
# (10)-(12) of the paper.  The Markov property is tested with local
# contingency tables (random projection + binning in the neighbourhood of every
# "present" state; modified log-likelihood statistic with Yates correction),
# aggregated over the neighbourhoods (clipped geometric mean by default, the
# paper's harmonic mean on request); the null distribution is generated by
# local permutations of the futures.  The neighbour searches run in C++
# (brute force, O(n^2)).

#' Select the memory (embedding dimension) of a series from its PACF
#'
#' The memory is the largest lag with a significant partial autocorrelation
#' (capped at `max_m`); a series with memory `m` becomes a first-order Markov
#' chain after time-delay embedding with dimension `m`.
#'
#' @param x numeric vector.
#' @param max_m largest memory considered.
#' @param alpha significance level of the PACF bands.
#' @return Integer memory (at least 1).
#' @references
#' Stippinger, M., Bencze, A., Zlatniczki, A., Somogyvari, Z. and Telcs, A. (2023). Causal discovery of stochastic dynamical systems: a Markov chain approach. *Mathematics*, 11(4), 852. \doi{10.3390/math11040852}
#' @export
#' @examples
#' # an AR(2) process: the partial autocorrelation cuts off after lag 2
#' set.seed(1); x <- as.numeric(stats::arima.sim(list(ar = c(.5, .3)), 500))
#' select_embedding(x)
select_embedding <- function(x, max_m = 3L, alpha = 0.05) {
  x <- as.numeric(x); n <- length(x)
  pc <- stats::pacf(x, lag.max = max(1L, max_m), plot = FALSE)$acf[, 1, 1]
  band <- stats::qnorm(1 - alpha / 2) / sqrt(n)
  sig <- which(abs(pc) > band)
  if (length(sig)) min(max(sig), max_m) else 1L
}

# local p-values (modified log-likelihood / Cressie-Read lambda = -1 with Yates)
.local_p_table <- function(bp, bf, b) {
  K <- ncol(bp)
  ra <- lapply(seq_len(b), function(a) rowSums(bp == a))
  cc <- lapply(seq_len(b), function(c) rowSums(bf == c))
  stat <- 0
  for (a in seq_len(b)) for (c in seq_len(b)) {
    O <- rowSums(bp == a & bf == c)
    E <- ra[[a]] * cc[[c]] / K
    d <- E - O
    Oy <- O + sign(d) * pmin(0.5, abs(d))
    term <- ifelse(E > 0, 2 * E * log(E / pmax(Oy, 1e-12)), 0)
    stat <- stat + term
  }
  nr <- Reduce(`+`, lapply(ra, function(v) v > 0)); nc <- Reduce(`+`, lapply(cc, function(v) v > 0))
  df <- (nr - 1) * (nc - 1)
  p <- ifelse(df > 0, stats::pchisq(pmax(stat, 0), pmax(df, 1), lower.tail = FALSE), 1)
  pmax(p, 1e-300)
}

.harmonic <- function(p) 1 / mean(1 / p)

# Discrete (symbolic) states: exact contingency tables conditional on the
# present state -- no neighbourhoods or projections are needed.
.markov_p_discrete <- function(A, n_perm = 99L, min_n = 20L, cores = 1L) {
  code <- function(M) as.integer(factor(apply(M, 1, paste, collapse = "|")))
  N <- nrow(A); i <- 2:(N - 1)
  pr <- code(A)[i]; pa <- code(A)[i - 1L]; fu <- code(A)[i + 1L]
  grp <- split(seq_along(i), pr); grp <- grp[lengths(grp) >= min_n]
  if (!length(grp)) stop("Too few observations per present state.", call. = FALSE)
  gstat <- function(pa, fu) {
    tab <- table(pa, fu); tab <- tab[rowSums(tab) > 0, colSums(tab) > 0, drop = FALSE]
    if (nrow(tab) < 2 || ncol(tab) < 2) return(1)
    E <- outer(rowSums(tab), colSums(tab)) / sum(tab)
    d <- E - tab; O <- tab + sign(d) * pmin(0.5, abs(d))     # Yates correction
    st <- 2 * sum(E * log(E / pmax(O, 1e-12)))
    max(stats::pchisq(max(st, 0), (nrow(tab) - 1) * (ncol(tab) - 1), lower.tail = FALSE), 1e-300)
  }
  hm <- function(fu_) .harmonic(vapply(grp, function(ix) gstat(pa[ix], fu_[ix]), 0))
  obs <- hm(fu)
  ref <- unlist(.plapply(seq_len(n_perm), function(r) {
    f2 <- fu; for (ix in grp) f2[ix] <- fu[ix][sample.int(length(ix))]; hm(f2) }, cores = cores))
  list(p_value = (1 + sum(ref <= obs)) / (n_perm + 1), statistic = obs, null = ref)
}

# Markov-property test of the state matrix A (rows = states in time order)
# Continuous states: Algorithms 1-2 of Stippinger et al. (2023).
# p_markov: for every interior state the K nearest states (max-norm, the
# state itself included) form the condition; their pasts and futures are
# projected on a random direction (a new one for every neighbourhood), binned
# into `b` quantile bins, and the 2-D contingency table is tested with the
# modified log-likelihood statistic (Yates-corrected).  The local p-values are
# aggregated (default: geometric mean of the clipped local p-values; the
# paper's harmonic mean is dominated by the few extreme neighbourhoods of
# near-deterministic systems and then over-rejects).  The
# reference distribution comes from local-permutation surrogates (Runge 2018):
# the future of every time index is replaced by the future of one of its
# k_perm nearest states, which keeps the information leaking through the
# finite neighbourhoods but destroys the dependence carried by hidden memory;
# p_value = P(statistic(surrogate) <= statistic(original)).
.markov_p <- function(A, k_nn = NULL, n_bins = 2L, n_perm = 99L, k_perm = 5L, cores = 1L,
                      aggregate = c("geometric", "median", "mean", "harmonic"), clip = 1e-4) {
  aggregate <- match.arg(aggregate)
  A <- as.matrix(A); N <- nrow(A); d <- ncol(A)
  if (N < 30) stop("Series too short for the Markov test.", call. = FALSE)
  if (all(apply(A, 2, function(v) length(unique(v))) <= 6L) && nrow(unique(A)) <= 64L)
    return(.markov_p_discrete(A, n_perm, cores = cores))
  A <- scale(A, center = TRUE, scale = apply(A, 2, stats::sd) + 1e-12)
  A <- .jit(.num_mat(A))
  interior <- 2:(N - 1); ni <- length(interior)
  K <- if (is.null(k_nn)) max(8L, ceiling(sqrt(N))) else as.integer(k_nn)
  K <- min(K, ni)
  b <- max(2L, as.integer(n_bins))
  agg <- switch(aggregate, harmonic = .harmonic, median = stats::median,
                mean = mean, geometric = function(p) exp(mean(log(pmax(p, clip)))))
  NN <- knn_idx_cpp(A[interior, , drop = FALSE], K - 1L)       # indices into `interior`
  idx <- matrix(interior[cbind(seq_len(ni), NN)], ni, K)       # time indices, self first
  p_markov <- function(fut) agg(markov_local_p_cpp(A, idx, fut, matrix(stats::rnorm(ni * d), ni, d),
                                                   matrix(stats::rnorm(ni * d), ni, d), b, stats::runif(ni * K)))
  fut0 <- seq_len(N) + 1L
  obs <- p_markov(fut0)
  nnk <- NN[, seq_len(min(max(2L, as.integer(k_perm)), K - 1L)), drop = FALSE]  # k_perm-NN within `interior`
  ref <- unlist(.plapply(seq_len(n_perm), function(r) {
    fut <- fut0; fut[interior] <- interior[.local_perm(nnk, ncol(nnk))] + 1L
    p_markov(fut)
  }, cores = cores))
  list(p_value = (1 + sum(ref <= obs)) / (n_perm + 1), statistic = obs, null = ref)
}

#' Test whether a series is a first-order Markov chain
#'
#' After time-delay embedding of dimension `m`, tests the Markov property
#' (past and future independent given the present) with the local
#' contingency-table procedure of Stippinger et al. (2023): for every state
#' the `k_nn` nearest states are collected, their pasts and futures are
#' randomly projected to one dimension and binned, a modified log-likelihood
#' (power divergence) test with Yates correction is applied, and the local
#' p-values are aggregated (`aggregate`: the clipped geometric mean by
#' default, or their median, mean or harmonic mean -- the latter as in the
#' paper). The reference distribution is obtained from
#' local-permutation surrogates (Runge 2018; Algorithm 1 of the paper): the
#' future of every time index is replaced by the future of one of its
#' `k_perm` nearest states, which keeps the information leaking through the
#' finite neighbourhoods but destroys the dependence carried by hidden memory.
#' For discrete (symbolic) states exact contingency tables conditional on the
#' present state are used instead.
#'
#' @param x numeric vector or matrix (columns = coordinates of the state).
#' @param m embedding dimension, or `"auto"` (from the PACF, see
#'   [select_embedding()]; only for vectors).
#' @param k_nn neighbourhood size (default `max(8, sqrt(n))`).
#' @param n_bins bins per projected variable (default 2, the rough binning
#'   of the paper's examples).
#' @param n_perm number of surrogates.
#' @param k_perm neighbourhood size of the local permutation.
#' @param aggregate aggregation of the local p-values: `"geometric"` (default:
#'   geometric mean of the local p-values clipped from below at `clip`, which
#'   keeps the broad shift of the local p-values but limits the influence of
#'   the few extreme neighbourhoods of near-deterministic series),
#'   `"median"`, `"mean"` or `"harmonic"` (harmonic mean, as in the paper).
#' @param clip lower clipping level of the local p-values for
#'   `aggregate = "geometric"`.
#' @param seed optional RNG seed.
#' @param cores CPU cores for the permutations (see [Rcausality-parallel]).
#' @return A list with `p_value` (small = not Markov), `statistic`
#'   (harmonic mean of local p-values), `m`.
#' @references
#' Stippinger, M., Bencze, A., Zlatniczki, A., Somogyvari, Z. and Telcs, A. (2023). Causal discovery of stochastic dynamical systems: a Markov chain approach. *Mathematics*, 11(4), 852. \doi{10.3390/math11040852}
#' @export
#' @examples
#' # An AR(1) process is first-order Markov: given x[t-1], x[t+1] carries no
#' # information about x[t-2], and the local permutation test accepts the
#' # Markov property (large p-value).
#' set.seed(1)
#' x <- as.numeric(stats::arima.sim(list(ar = 0.6), 400))
#' markov_test(x, m = 1, n_perm = 49)$p_value
#' \donttest{
#' # the same series is not Markov of order 1 after a lag-2 dependence is added
#' y <- x + c(0, 0, 0.8 * x[-(399:400)])
#' markov_test(y, m = 1, n_perm = 49)$p_value      # small: order 1 is not enough
#' markov_test(y, m = "auto", n_perm = 49)$m       # the PACF picks a deeper memory
#' }
markov_test <- function(x, m = "auto", k_nn = NULL, n_bins = 2L, n_perm = 99L, k_perm = 5L,
                        aggregate = c("geometric", "median", "mean", "harmonic"), clip = 1e-4,
                        seed = NULL, cores = getOption("Rcausality.cores", 1L)) {
  aggregate <- match.arg(aggregate)
  old <- .rng_setup(seed); on.exit(.rng_restore(old), add = TRUE)
  if (is.matrix(x) || is.data.frame(x)) { A <- as.matrix(x); m <- 1L } else {
    if (identical(m, "auto")) m <- select_embedding(x)
    A <- embed_delay(x, m, 1L)
  }
  r <- .markov_p(A, k_nn, n_bins, n_perm, k_perm = k_perm, cores = cores, aggregate = aggregate, clip = clip)
  r$m <- m
  r
}

# Decision tables (10)-(12) of the paper. MA/MB/MJ: Markov property not rejected
# for A = x, B = y and the joint; sAB/sBA: directed dependence A->B, B->A
# significant. Verdicts: "n" none, "i.i." i.i.d. injection, "n.i." non-i.i.d.
# injection, "d" driving of unspecified kind.
.markov_decide <- function(MA, MB, MJ, sAB, sBA, sI0, iid = "allowed") {
  ab <- "n"; ba <- "n"; hidden <- character(0); ok <- TRUE
  if (MJ) {
    if (iid == "forbidden") {
      if (!MA) ab <- "n.i."   # placeholder, set below by direction of non-Markov series
      ab <- "n"; ba <- "n"
      # A not Markov: B drives A (B->A) ; B not Markov: A drives B
      if (!MA) ba <- "n.i."
      if (!MB) ab <- "n.i."
    } else if (MA && MB) {
      ab <- if (sAB) "i.i." else "n"; ba <- if (sBA) "i.i." else "n"
    } else if (!MA && MB) {
      if (!sAB && sBA) ba <- "n.i."
      else if (sAB && sBA) { ab <- "i.i."; ba <- "n.i." } else ok <- FALSE
    } else if (MA && !MB) {
      if (sAB && !sBA) ab <- "n.i."
      else if (sAB && sBA) { ab <- "n.i."; ba <- "i.i." } else ok <- FALSE
    } else {
      if (sAB && sBA) { ab <- "n.i."; ba <- "n.i." } else ok <- FALSE
    }
  } else {
    if (MA && MB) {
      ok <- FALSE
    } else if (MA && !MB) {
      hidden <- "U_B"
      if (sAB && !sBA) ab <- "d"
      else if (sAB && sBA) { ab <- "d"; ba <- "i.i." }
      else if (sBA && !sAB) ok <- FALSE
    } else if (!MA && MB) {
      hidden <- "U_A"
      if (sBA && !sAB) ba <- "d"
      else if (sAB && sBA) { ba <- "d"; ab <- "i.i." }
      else if (sAB && !sBA) ok <- FALSE
    } else {
      if (sAB) ab <- "d"; if (sBA) ba <- "d"
      hidden <- if (!sAB && !sBA && !sI0) "U_A and U_B"
                else if (sAB && !sBA && !sI0) "U_A"
                else if (!sAB && sBA && !sI0) "U_B"
                else if (sAB && sBA && !sI0) "U_A or U_B (undetermined)"
                else "Z or eps (not separable from U_A/U_B)"
    }
  }
  if (!ok) { ab <- if (sAB) "d" else "n"; ba <- if (sBA) "d" else "n" }
  list(ab = ab, ba = ba, common = sI0, hidden = paste(hidden, collapse = ""),
       consistent = ok,
       case = sprintf("J=%s x=%s y=%s", if (MJ) "M" else "N", if (MA) "M" else "N", if (MB) "M" else "N"))
}

# One unordered pair (x, y): Markov tests + directed/instant CMI tests
.markov_pair <- function(x, y, memory, k_nn, n_bins, n_markov, k, k_perm, n_perm, cores = 1L) {
  m <- if (identical(memory, "auto")) max(select_embedding(x), select_embedding(y)) else as.integer(memory)
  Ex <- embed_delay(x, m, 1L); Ey <- embed_delay(y, m, 1L); N <- nrow(Ex)
  pm <- function(A) .markov_p(A, k_nn, n_bins, n_markov, k_perm = k_perm, cores = cores)
  mx <- pm(Ex); my <- pm(Ey); mj <- pm(cbind(Ex, Ey))
  p_jm1 <- pm(cbind(Ex[1:(N - 1), , drop = FALSE], Ey[2:N, , drop = FALSE]))$p_value  # x earlier
  p_jp1 <- pm(cbind(Ex[2:N, , drop = FALSE], Ey[1:(N - 1), , drop = FALSE]))$p_value  # x later
  xy <- .cmi_pair(y, x, NULL, 1L, m, k, k_perm, n_perm, cause_past = TRUE, cores = cores)
  yx <- .cmi_pair(x, y, NULL, 1L, m, k, k_perm, n_perm, cause_past = TRUE, cores = cores)
  i0 <- .cmi_instant(x, y, NULL, m, k, k_perm, n_perm, cores = cores)
  list(m = m, p_x = mx$p_value, p_y = my$p_value, p_j = mj$p_value, p_jm1 = p_jm1, p_jp1 = p_jp1,
       xy = xy, yx = yx, i0 = i0,
       null = list(x = list(statistic = mx$statistic, null = mx$null, alternative = "less"),
                   y = list(statistic = my$statistic, null = my$null, alternative = "less"),
                   j = list(statistic = mj$statistic, null = mj$null, alternative = "less"),
                   xy = list(statistic = xy$statistic, null = xy$null, alternative = "greater"),
                   yx = list(statistic = yx$statistic, null = yx$null, alternative = "greater"),
                   i0 = list(statistic = i0$cmi, null = i0$null, alternative = "greater")))
}
